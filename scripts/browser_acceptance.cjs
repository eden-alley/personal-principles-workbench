/* Optional browser acceptance. Requires Playwright and Edge; the app itself does not. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const BASE = process.env.WORKBENCH_TEST_URL || 'http://127.0.0.1:8766';
const output = path.resolve('artifacts');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const results = [];
  async function submit(name, pattern) {
    await Promise.all([page.waitForURL(pattern), page.getByRole('button', { name, exact: true }).click()]);
    assert.equal(await page.locator('.form-errors').count(), 0);
  }
  const confirm = async () => page.locator('#id_confirmed').check();
  try {
    await page.goto(BASE);
    await page.getByRole('link', { name: /存一个想法/ }).click();
    await page.locator('#id_text').fill('【浏览器验收虚构素材】当社交邀请与阅读安排冲突时，可以先讨论时间，而不是直接放弃阅读。');
    await page.locator('#id_title').fill('浏览器验收：阅读与邀请（虚构）');
    await submit('保存素材', /\/sources\/\d+\/$/);
    const sourceUrl = page.url();
    assert.match(await page.locator('.source-copy').innerText(), /虚构素材/);
    results.push('原文先保存');
    await page.getByRole('link', { name: '提炼原则', exact: true }).click();
    await submit('生成演示建议', /\/suggestions\/\d+\/$/);
    assert.match(await page.locator('main').innerText(), /演示数据 \/ 非真实模型输出/);
    await page.locator('#id_title').fill('保护可以协商的阅读时间（演示）');
    await page.locator('#id_statement').fill('当阅读安排与邀请冲突时，先尝试改约。');
    await page.locator('#id_when_to_use').fill('阅读安排与邀请冲突');
    await page.locator('#id_status').selectOption('adopted');
    await page.locator('#id_reason').fill('这是一条演示流程的候选想法，由测试明确采纳。');
    await confirm();
    await submit('确认保存', /\/principles\/\d+\/$/);
    const principleUrl = page.url();
    const oldVersionUrl = await page.locator('.version-list a').first().getAttribute('href');
    assert.match(await page.locator('main').innerText(), /已采纳/);
    results.push('演示提炼 → 编辑并明确采纳');
    await page.goto(BASE + '/cases/new/');
    await page.locator('#id_situation').fill('【浏览器验收虚构情境】周末阅读时间和朋友邀请冲突，我可以讨论改约吗？');
    await submit('保存情境', /\/cases\/\d+\/$/);
    const caseUrl = page.url();
    assert.match(await page.locator('main').innerText(), /保护可以协商的阅读时间/);
    await page.locator('#id_content').fill('这是普通邀请，对方有其他空闲时间。');
    await submit('保存补充', /\/cases\/\d+\/$/);
    await page.getByRole('link', { name: '预览 AI 整理', exact: true }).click();
    await submit('生成演示建议', /\/suggestions\/\d+\/$/);
    assert.match(await page.locator('main').innerText(), /演示数据 \/ 非真实模型输出/);
    await page.goto(caseUrl);
    assert.match(await page.locator('.message-list').innerText(), /真实模型输出/);
    results.push('关键词检索真实版本 → 情境补充 → 演示对话');
    await page.getByRole('link', { name: '记录选择', exact: true }).click();
    await page.locator('#id_choice').fill('先提出改约到晚餐时间。');
    await page.locator('#id_reason').fill('希望兼顾阅读与关系，这条理由必须保持不变。');
    await page.locator('#id_expectation').fill('保留自主空间，也让关系更自在。');
    await page.locator('#id_review_date').fill('2026-10-15');
    await confirm();
    await submit('确认保存', /\/decisions\/\d+\/$/);
    const decisionUrl = page.url();
    assert.match(await page.locator('.citation-list').innerText(), /版本 1/);
    await page.getByRole('link', { name: '添加观察', exact: true }).click();
    assert.match(await page.locator('.lede').innerText(), /这条理由必须保持不变/);
    await page.locator('#id_facts').fill('【虚构验收观察】朋友同意改约，阅读也完成了。');
    await page.locator('#id_interpretation').fill('协商时间可能有帮助。');
    await page.locator('#id_uncertainty').fill('其他关系和邀请不一定一样。');
    await page.locator('#id_difference').fill('比预想更容易协商。');
    await page.locator('#id_effect').selectOption('supports');
    await confirm();
    await submit('确认保存', /\/observations\/\d+\/$/);
    const observationUrl = page.url();
    const reviseLink = page.locator('a[href*="/ai/preview/revise/"]').first();
    await reviseLink.click();
    await submit('生成演示建议', /\/suggestions\/\d+\/$/);
    assert.match(await page.locator('main').innerText(), /修订前的当前版本/);
    await page.locator('#id_statement').fill('当阅读与普通邀请冲突时，先协商时间；重要支持情境另作考虑。');
    await page.locator('#id_reason').fill('这次演示经历提示可以补充情境边界，并不构成验证。');
    await confirm();
    await submit('确认保存', /\/principles\/\d+\/$/);
    assert.match(await page.locator('.version-list').innerText(), /版本 2/);
    await page.goto(decisionUrl);
    assert.match(await page.locator('.citation-list').innerText(), /版本 1/);
    assert.match(await page.locator('main').innerText(), /这条理由必须保持不变/);
    await page.locator('.citation-list a').first().click();
    assert.equal(new URL(page.url()).pathname, oldVersionUrl);
    assert.match(await page.locator('main').innerText(), /当阅读安排与邀请冲突时，先尝试改约。/);
    results.push('选择固定 v1 → 后续观察 → 确认修订 v2 → 旧选择仍引用 v1');
    await page.goto(principleUrl);
    await page.screenshot({ path: path.join(output, 'principle-desktop.png'), fullPage: true });
    await page.goto(BASE);
    await page.screenshot({ path: path.join(output, 'home-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.getElementById('side-nav').getBoundingClientRect().right <= 0);
    await page.screenshot({ path: path.join(output, 'home-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '手机横向溢出');
    await page.getByRole('button', { name: '导航', exact: true }).click();
    await page.getByRole('link', { name: '素材库', exact: true }).click();
    assert.match(page.url(), /\/sources\/$/);
    await page.goto(principleUrl);
    await page.screenshot({ path: path.join(output, 'principle-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '详情页手机横向溢出');
    assert.deepEqual(errors, []);
    const report = { results, sourceUrl, principleUrl, caseUrl, decisionUrl, observationUrl, oldVersionUrl, browserErrors: errors, demoOnly: true };
    fs.writeFileSync(path.join(output, 'browser-acceptance.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'browser-failure.png'), fullPage: true });
    console.error('FAIL at', page.url(), '\n', error);
    process.exitCode = 1;
  } finally {
    await browser.close();
  }
})();
